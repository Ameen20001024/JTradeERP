namespace JTradeERP.Application.Features.Billing;

public static class BillingEndpointExtensions
{
    public static IEndpointRouteBuilder MapBillingEndpoints(this IEndpointRouteBuilder endpoints)
    {
        var group = endpoints.MapGroup("/api/billing").RequireAuthorization();
        CreateQuotationEndPoint.Map(group);
        SendQuotationEndPoint.Map(group);
        AcceptQuotationEndPoint.Map(group);
        ConvertQuotationToSalesOrderEndPoint.Map(group);
        RejectQuotationEndPoint.Map(group);
        CancelQuotationEndPoint.Map(group);
        UpdateQuotationEndPoint.Map(group);
        GetQuotationByIdEndPoint.Map(group);
        PrintQuotationEndPoint.Map(group);
        GetQuotationsEndPoint.Map(group);
        ExpireQuotationEndPoint.Map(group);
        CopyQuotationEndPoint.Map(group);
        CreateSalesOrderEndPoint.Map(group);
        PostSalesOrderEndPoint.Map(group);
        CancelSalesOrderEndPoint.Map(group);
        GetSalesOrderByIdEndPoint.Map(group);
        GetSalesOrdersEndPoint.Map(group);
        UpdateSalesOrderEndPoint.Map(group);
        CreateInvoiceEndPoint.Map(group);
        PostInvoiceEndPoint.Map(group);
        CancelInvoiceEndPoint.Map(group);
        GetInvoiceByIdEndPoint.Map(group);
        PrintInvoiceEndPoint.Map(group);
        GetInvoicesEndPoint.Map(group);
        UpdateInvoiceEndPoint.Map(group);
        RecordPaymentEndPoint.Map(group);
        ReversePaymentEndPoint.Map(group);
        CreateCreditNoteEndPoint.Map(group);
        PostCreditNoteEndPoint.Map(group);
        GetCreditNoteByIdEndPoint.Map(group);
        GetCreditNotesEndPoint.Map(group);
        UpdateCreditNoteEndPoint.Map(group);
        CancelCreditNoteEndPoint.Map(group);
        GetBillingConfigurationEndPoint.Map(group);
        UpdateBillingConfigurationEndPoint.Map(group);
        CreatePaymentMethodEndPoint.Map(group);
        GetPaymentMethodsEndPoint.Map(group);
        ActivatePaymentMethodEndPoint.Map(group);
        DeactivatePaymentMethodEndPoint.Map(group);
        UpdatePaymentMethodEndPoint.Map(group);
        DeletePaymentMethodEndPoint.Map(group);
        GetPaymentMethodByIdEndPoint.Map(group);
        GetPaymentsEndPoint.Map(group);
        GetPaymentByIdEndPoint.Map(group);
        CreateNumberSeriesEndPoint.Map(group);
        GetNumberSeriesEndPoint.Map(group);
        UpdateNumberSeriesEndPoint.Map(group);
        GetNumberSeriesByIdEndPoint.Map(group);
        DeleteNumberSeriesEndPoint.Map(group);
        return endpoints;
    }
}
